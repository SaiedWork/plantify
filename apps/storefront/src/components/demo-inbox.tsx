"use client";

import { createContext, useContext, useEffect, useState, type ReactNode } from "react";
import { Mail } from "lucide-react";
import { Button } from "@/components/ui/button";
import {
  Sheet,
  SheetContent,
  SheetDescription,
  SheetHeader,
  SheetTitle,
} from "@/components/ui/sheet";

type Message = {
  id: string;
  to: string;
  subject: string;
  html: string;
  otp: string | null;
  createdAt: string;
};

const InboxContext = createContext<{ open: () => void }>({ open: () => {} });
export const useDemoInbox = () => useContext(InboxContext);

/** Stands in for a real mailbox: this demo never sends email to the internet. */
export function DemoInboxProvider({ children }: { children: ReactNode }) {
  const [isOpen, setOpen] = useState(false);
  const [messages, setMessages] = useState<Message[]>([]);
  const [selected, setSelected] = useState<string | null>(null);

  useEffect(() => {
    if (!isOpen) return;
    let cancelled = false;
    const load = async () => {
      try {
        const res = await fetch("/api/demo-inbox", { cache: "no-store" });
        if (res.ok && !cancelled) setMessages((await res.json()).messages);
      } catch {
        // transient network error: the next poll retries
      }
    };
    void load();
    const timer = setInterval(load, 2000);
    return () => {
      cancelled = true;
      clearInterval(timer);
    };
  }, [isOpen]);

  const current = messages.find((m) => m.id === selected);

  return (
    <InboxContext.Provider value={{ open: () => setOpen(true) }}>
      {children}
      <Sheet open={isOpen} onOpenChange={setOpen}>
        <SheetContent className="w-full overflow-y-auto sm:max-w-md">
          <SheetHeader>
            <SheetTitle>Demo inbox</SheetTitle>
            <SheetDescription>
              Plantify is a demo, so emails land here instead of a real mailbox.
            </SheetDescription>
          </SheetHeader>
          <div className="px-4 pb-4">
            {current ? (
              <div className="space-y-3">
                <Button variant="ghost" size="sm" onClick={() => setSelected(null)}>
                  ← Back
                </Button>
                <p className="text-sm text-muted-foreground">To: {current.to}</p>
                <h3 className="font-medium">{current.subject}</h3>
                {/* Content is generated by our own server, never user-supplied HTML. */}
                <div
                  className="rounded-md border p-3"
                  dangerouslySetInnerHTML={{ __html: current.html }}
                />
              </div>
            ) : messages.length === 0 ? (
              <p className="py-8 text-center text-sm text-muted-foreground">
                No messages yet. Request a code and it will appear here.
              </p>
            ) : (
              <ul className="divide-y rounded-md border">
                {messages.map((m) => (
                  <li key={m.id}>
                    <button
                      type="button"
                      onClick={() => setSelected(m.id)}
                      className="w-full px-3 py-2 text-left hover:bg-muted"
                    >
                      <p className="truncate text-sm font-medium">{m.subject}</p>
                      <p className="truncate text-xs text-muted-foreground">
                        {m.to} · {new Date(m.createdAt).toLocaleTimeString()}
                      </p>
                    </button>
                  </li>
                ))}
              </ul>
            )}
          </div>
        </SheetContent>
      </Sheet>
    </InboxContext.Provider>
  );
}

export function DemoInboxButton() {
  const { open } = useDemoInbox();
  return (
    <Button variant="outline" size="sm" onClick={open}>
      <Mail className="size-4" /> Demo inbox
    </Button>
  );
}
